#!/usr/bin/env python3
"""
generate-kueue-agnostic.py — emit the product-agnostic Kueue static layer
(deviceClassMappings + CQ/cohort lane entries) from the fork's GPU profile
catalog — the SAME source hack/sync-profiles.sh consumes (single source of
truth: the static layer can never drift from what the mock can serve).

Design (see ~/.opencode/plan/kueue-agnostic-quota-matrix.md): the static
layer speaks PROFILE, never PRODUCT. One fold entry (`gpu`) plus one lane
per MIG profile in the catalog (`mig-<profile>`), so a product swap via the
gpu-config-plugin finds its mapping and lanes ALREADY PRESENT — Kueue is
never edited and never restarted again after the one-time landing.

Usage:
  python3 generate-kueue-agnostic.py                # fragments to stdout
  python3 generate-kueue-agnostic.py --outdir DIR   # fragments written as files
  SYNC_LOCAL_DIR=~/git/k8s-test-infra python3 ...   # fork source (default)

Deterministic: sorted output, no timestamps.
"""
import argparse
import glob
import os
import re
import sys

import yaml

DEFAULT_SOURCE = os.path.expanduser("~/git/k8s-test-infra/deployments/nvml-mock/helm/nvml-mock/profiles")
FOLD_NAME = "gpu"


def sanitize(name: str) -> str:
    """Profile '7g.141gb' -> k8s-name-safe 'mig-7g-141gb'.

    Non-[a-z0-9-] collapses to '-' (mirrors the app's migDeviceClassName).
    """
    return re.sub(r"[^a-z0-9-]+", "-", name.lower()).strip("-")


# Media-extension variants (+me / -me / +me.all) are EXCLUDED per Mike's
# decision (2026-11-26): not part of the product surface the lab demos,
# and their '+' spellings are illegal in k8s names anyway. The live H200/
# H100/A100 surfaces publish only base profiles. (The vrnvl72 tables spell
# the all-instances variant "+me.all" — dot, not dash — hence the (\.all)?)
VARIANT_RE = re.compile(r"(\+me|-me)(\.all|-all)?$")


def load_catalog(source: str, products_filter=None):
    """Read every MIG table from the profile tree: profile name -> sorted
    set of products that ship it. Media-extension variants are filtered.
    products_filter limits the matrix to the named products — the RH Kueue
    operator's Kueue CR caps deviceClassMappings at 16 entries (live
    finding 2026-11-26: the 37-entry full-catalog matrix was rejected by
    the CR's OpenAPI validation), so the matrix covers the demo products
    (default h200+h100, the swap pair) and is regenerated when the set
    changes (one GitOps commit + the documented operand restart)."""
    mig_dir = os.path.join(source, "mig")
    if not os.path.isdir(mig_dir):
        sys.exit(f"error: no mig/ dir under {source} (pass SYNC_LOCAL_DIR)")
    lanes = {}
    products = []
    skipped = set()
    for path in sorted(glob.glob(os.path.join(mig_dir, "*.yaml"))):
        product = os.path.basename(path)[: -len(".yaml")]
        if products_filter and product not in products_filter:
            continue
        products.append(product)
        doc = yaml.safe_load(open(path))
        for sp in (doc.get("supported_profiles") or []) if isinstance(doc, dict) else []:
            name = sp.get("name", "")
            if not name:
                continue
            if VARIANT_RE.search(name):
                skipped.add(name)
                continue
            lanes.setdefault(sanitize(name), {"profiles": set(), "products": set()})
            lanes[sanitize(name)]["profiles"].add(name)
            lanes[sanitize(name)]["products"].add(product)
    return products, lanes, sorted(skipped)


def mapping_block(lanes) -> str:
    """The kueue-cr deviceClassMappings entries: the fold (whole + shared
    MIG class -> gpu) plus one entry per catalog profile class."""
    lines = [
        "        # Product-agnostic DRA quota mapping — GENERATED by",
        "        # hack/generate-kueue-agnostic.py from the fork profile catalog.",
        "        # One fold (whole devices + the shared MIG class charge the",
        "        # whole lane) plus one entry per catalog MIG profile, so ANY",
        "        # product swap via the gpu-config-plugin finds its mapping",
        "        # already present: Kueue is never edited/restarted for swaps.",
        "        # Names speak PROFILE (mig-<profile>), never product.",
        "        - name: " + FOLD_NAME,
        "          deviceClassNames:",
        "            - gpu.nvidia.com",
        "            - mig.nvidia.com",
    ]
    for lane in sorted(lanes):
        lines.append(f"        - name: {lane}")
        lines.append("          deviceClassNames:")
        lines.append(f"            - mig.nvidia.com-{lane}")
    return "\n".join(lines)


def lane_block(lanes) -> str:
    """The kueue-queues CQ/cohort lane names (zeroed nominal; the booking
    app's applyCohortRemaining owns capacity for ACTIVE lanes only)."""
    lines = [
        "        # Product-agnostic DRA lanes — GENERATED by",
        "        # hack/generate-kueue-agnostic.py from the fork profile catalog.",
        "        # Zeroed nominal: capacity lives in the Cohort and is written by",
        "        # the booking app's reservation sync for ACTIVE lanes only, so",
        "        # inactive products' entries never borrow. Never edit by hand:",
        "        # re-run the generator when the profile catalog changes.",
        f"        - {FOLD_NAME}",
    ]
    lines.extend(f"        - {lane}" for lane in sorted(lanes))
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--outdir", help="write fragments as files instead of stdout")
    ap.add_argument("--source", default=os.environ.get("SYNC_LOCAL_DIR", DEFAULT_SOURCE))
    ap.add_argument(
        "--products",
        default=os.environ.get("KUEUE_MATRIX_PRODUCTS", "h200,h100"),
        help="comma-separated products to cover (default h200,h100 — the demo "
        "swap pair; the Kueue CR caps deviceClassMappings at 16 entries)",
    )
    args = ap.parse_args()
    products_filter = {p.strip() for p in args.products.split(",") if p.strip()}

    products, lanes, skipped = load_catalog(args.source, products_filter)
    if len(lanes) + 1 > 16:
        sys.exit(
            f"error: {len(lanes) + 1} mapping entries exceed the Kueue CR's "
            "16-item deviceClassMappings cap — trim --products"
        )
    blocks = {
        "kueue-cr.deviceClassMappings.yaml": mapping_block(lanes),
        "kueue-queues.lanes.yaml": lane_block(lanes),
    }
    header = (
        f"# products: {len(products)} ({', '.join(products)})\n"
        f"# lanes: {len(lanes)} agnostic + 1 fold = {len(lanes) + 1} mapping entries\n"
        f"# excluded media-extension variants: {', '.join(skipped) if skipped else '(none)'}\n"
    )
    if args.outdir:
        os.makedirs(args.outdir, exist_ok=True)
        for fname, block in blocks.items():
            with open(os.path.join(args.outdir, fname), "w") as fh:
                fh.write(header + "\n" + block + "\n")
        print(header + f"fragments written to {args.outdir}/")
    else:
        sys.stdout.write(header + "\n")
        for fname, block in blocks.items():
            sys.stdout.write(f"=== {fname} ===\n{block}\n\n")


if __name__ == "__main__":
    main()
